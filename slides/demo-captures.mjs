// Writes slides/captures.js from the gateway demo's sessions.json: an array of { key, steps: [{ cmd, out }] },
// recorded by the demo's run-demo.sh. Nothing is filtered; the deck shows each session whole.
// Run: node slides/demo-captures.mjs <path to sessions.json>
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
const here = dirname(fileURLToPath(import.meta.url));
const source = process.argv[2];
if (!source) { console.error('usage: node slides/demo-captures.mjs <sessions.json>'); process.exit(2); }
const sessions = JSON.parse(readFileSync(source, 'utf8'));
if (!Array.isArray(sessions) || !sessions.every((s) => typeof s.key === 'string' && Array.isArray(s.steps))) throw new Error('sessions.json is not an array of { key, steps }');
const strip = (text) => String(text).replace(/\x1b\[[0-9;]*m/g, '');
const lines = [`// Generated by slides/demo-captures.mjs on ${new Date().toISOString()} from the gateway demo. Do not edit.`, 'window.CAPTURES = {};'];
for (const { key, steps } of sessions) {
  lines.push(`window.CAPTURES[${JSON.stringify(key)}] = ${JSON.stringify(steps.map(({ cmd, out }) => ({ cmd: strip(cmd), out: strip(out ?? '') })))};`);
}
writeFileSync(join(here, 'captures.js'), lines.join('\n') + '\n');
console.log(`wrote slides/captures.js (${sessions.length} sessions)`);
