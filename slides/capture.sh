#!/usr/bin/env bash
# Regenerates slides/captures.js by replaying the lab commands in a throwaway worktree, the same way labs/verify.sh
# does. Each capture is a terminal session: the commands exactly as the labs print them, each with its output as it
# came out, nothing filtered apart from colour codes, so a pane on a slide shows what the repository does today when
# you type the same thing. Narrowing is done by the command itself (head, tail, awk, grep), never by this script.
# Usage: bash slides/capture.sh
set -euo pipefail
ROOT=$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)
OUT="$ROOT/slides/captures.js"
cd "$ROOT"
[ -d node_modules ] || { echo "run npm install first"; exit 2; }
unset BASE_REF SPEC PR_BODY CHANGE_AUTHOR_KIND CHANGE_AUTHOR_ID
export GIT_AUTHOR_NAME=lab-runner GIT_AUTHOR_EMAIL=lab-runner@example.invalid GIT_COMMITTER_NAME=lab-runner GIT_COMMITTER_EMAIL=lab-runner@example.invalid NODE_NO_WARNINGS=1 NO_COLOR=1

WT=$(mktemp -d "${TMPDIR:-/tmp}/blueprint-capture.XXXXXX")
WT=$(cd "$WT" && pwd -P)
cleanup() { cd "$ROOT"; git worktree remove --force "$WT" >/dev/null 2>&1 || true; rm -rf "$WT"; }
trap cleanup EXIT
git worktree add --detach -q "$WT" HEAD
ln -s "$ROOT/node_modules" "$WT/node_modules"
if [ -n "$(git status --porcelain)" ]; then     # capture what you are about to commit, not just HEAD
  git diff --binary HEAD > "$WT/.capture.diff"
  [ -s "$WT/.capture.diff" ] && git -C "$WT" apply "$WT/.capture.diff"
  git ls-files --others --exclude-standard -z | while IFS= read -r -d '' f; do mkdir -p "$WT/$(dirname "$f")"; cp "$f" "$WT/$f"; done
  rm "$WT/.capture.diff"
  git -C "$WT" add -A
fi
cd "$WT"
git commit -q --allow-empty -m "capture baseline"

TMP=$(mktemp)
echo "// Generated by slides/capture.sh on $(date -u +%FT%TZ). Do not edit." > "$TMP"
echo "window.CAPTURES = {};" >> "$TMP"
cap() {                       # cap KEY "<command>"...   one session: each command verbatim, with its output
  local key=$1; shift
  local session="[]" cmd out
  for cmd in "$@"; do
    echo "\$ $cmd"
    out=$(bash -c "$cmd" 2>&1 | sed -E 's/\x1b\[[0-9;]*m//g' | sed "s#$WT#.#g" || true)
    session=$(node -e 'const [s,c,o]=process.argv.slice(1);const a=JSON.parse(s);a.push({cmd:c,out:o});process.stdout.write(JSON.stringify(a))' "$session" "$cmd" "$out")
  done
  node -e 'const [k,v]=process.argv.slice(1);process.stdout.write(`window.CAPTURES[${JSON.stringify(k)}] = ${v};\n`)' "$key" "$session" >> "$TMP"
}
quiet() { "$@" >/dev/null 2>&1; }   # resets between captures that no slide shows


# Lab 2: spec
cap spec-front-matter "head -n 8 specs/SPEC-001-account-summary.md"
cap context "npm run calm:context -- --spec SPEC-001 | awk '/\"scope\"/,/\"nodeControls\"/'" "npm run calm:context -- --spec SPEC-001 | tail -n 2"
cap gate-spec "npm run gate:spec"
cap gate-spec-unknown "git apply labs/patches/spec-001-unknown-node.patch" "npm run gate:spec" "git checkout specs/"

# Lab 3: agent
cap agents-md "head -n 16 AGENTS.md"
cap attempt-a-apply "git apply labs/patches/attempt-a-shortcut.patch" "git diff -- services/trade-api/src/config.ts"
cap attempt-a-tests "npm test && npm run typecheck"
cap attempt-a-gates "SPEC=SPEC-001 npm run gates"
cap attempt-b-apply "git checkout -- . && git clean -fd services test" "git apply labs/patches/attempt-b-conformant.patch" "grep -n positionServiceUrl services/trade-api/src/app.ts"
cap attempt-b-gates "SPEC=SPEC-001 npm run gates"

# Lab 4: gate
cap review-cognitive "npm run gate:review"
cap review-human 'echo "// touched by lab 4" >> services/position-service/src/app.ts' "npm run gate:review" "git checkout -- services/position-service/src/app.ts"
cap review-policy "grep -n -e '\"author-may-not-review\"' -e '\"mode\"' -e '\"reason\"' architecture/trade-capture.architecture.json"
cap attempt-c-apply "git checkout -- . && git clean -fd services test" "git apply labs/patches/attempt-c-edit-the-model.patch"
cap attempt-c-gates "SPEC=SPEC-001 npm run gates"
cap spec-002-model "git checkout -- . && git clean -fd services test specs" "git apply labs/patches/spec-002-model-change.patch" "SPEC=SPEC-002 npm run gates"
cap spec-002-impl "git apply labs/patches/attempt-d-spec-002.patch" "SPEC=SPEC-002 npm run gates"

# Lab 5: evidence
cap evidence "git checkout -- . && git clean -fd services test specs" "git apply labs/patches/attempt-b-conformant.patch" 'git add -A && git commit -m "Add account summary endpoint" -m "Spec: SPEC-001"' "CHANGE_AUTHOR_KIND=agent CHANGE_AUTHOR_ID=my-coding-agent npm run evidence"
cap evidence-bundle 'head -n 24 evidence/out/$(git rev-parse --short=12 HEAD).json'
cap evidence-docs 'ls evidence/out/$(git rev-parse --short=12 HEAD)/' 'cat evidence/out/$(git rev-parse --short=12 HEAD)/*.sdlc-prev-012-deployment-gating.json'

mv "$TMP" "$OUT"
echo "wrote $OUT ($(grep -c 'window.CAPTURES\[' "$OUT") captures)"
