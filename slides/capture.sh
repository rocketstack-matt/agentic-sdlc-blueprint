#!/usr/bin/env bash
# Regenerates slides/captures.js by replaying the lab commands in a throwaway worktree, the same way labs/verify.sh
# does, so every terminal pane in the deck shows what the repository does today. Usage: bash slides/capture.sh
set -euo pipefail
ROOT=$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)
OUT="$ROOT/slides/captures.js"
cd "$ROOT"
[ -d node_modules ] || { echo "run npm install first"; exit 2; }
unset BASE_REF SPEC PR_BODY CHANGE_AUTHOR_KIND CHANGE_AUTHOR_ID
export GIT_AUTHOR_NAME=lab-runner GIT_AUTHOR_EMAIL=lab-runner@example.invalid GIT_COMMITTER_NAME=lab-runner GIT_COMMITTER_EMAIL=lab-runner@example.invalid NODE_NO_WARNINGS=1

WT=$(mktemp -d "${TMPDIR:-/tmp}/blueprint-capture.XXXXXX")
WT=$(cd "$WT" && pwd -P)
cleanup() { cd "$ROOT"; git worktree remove --force "$WT" >/dev/null 2>&1 || true; rm -rf "$WT"; }
trap cleanup EXIT
git worktree add --detach -q "$WT" HEAD
ln -s "$ROOT/node_modules" "$WT/node_modules"
cd "$WT"
git commit -q --allow-empty -m "capture baseline"

TMP=$(mktemp)
echo "// Generated by slides/capture.sh on $(date -u +%FT%TZ). Do not edit." > "$TMP"
echo "window.CAPTURES = {};" >> "$TMP"
cap() {                       # cap KEY "<command>"   records stdout+stderr, minus npm's own banner lines
  local key=$1; shift
  echo "\$ $*"
  local out; out=$(bash -c "$*" 2>&1 | grep -vE '^(> |$)' | sed "s#$WT#.#g" || true)
  node -e 'const [k,v]=process.argv.slice(1);process.stdout.write(`window.CAPTURES[${JSON.stringify(k)}] = ${JSON.stringify(v)};\n`)' "$key" "$out" >> "$TMP"
}

cap clean-gates "npm run gates"
node -e "const fs=require('fs');const p='architecture/trade-capture.architecture.json';const a=JSON.parse(fs.readFileSync(p));delete a.nodes.find(n=>n['unique-id']==='trade-api').metadata['source-path'];fs.writeFileSync(p,JSON.stringify(a,null,2)+'\n')"
cap lab1-break-pattern "npm run calm:validate 2>&1 | grep -vE '^\S*info' | sed -E 's/\x1b\[[0-9;]*m//g' | grep -E \"^(- Errors|ERROR issues|  ERROR)\""
git checkout -q architecture/
cap context "npm run calm:context -- --spec SPEC-001 2>&1 | node -e \"let s='';process.stdin.on('data',d=>s+=d).on('end',()=>{const j=JSON.parse(s.slice(s.indexOf('{')));const t=j.scope[0];console.log(JSON.stringify({node:t.node.id,mayConnectTo:t.mayConnectTo.map(m=>m.node),mustNotConnectTo:t.mustNotConnectTo,rule:j.rule},null,2))})\""

git apply labs/patches/attempt-a-shortcut.patch
cap attempt-a-tests "npm test 2>&1 | grep -E '^(✔|✖|ℹ (tests|pass|fail)|ok |not ok |# (tests|pass|fail))'"
cap attempt-a-gates "SPEC=SPEC-001 npm run gates"
git checkout -q -- . && git clean -fdq services test

git apply labs/patches/attempt-b-conformant.patch
cap attempt-b-gates "SPEC=SPEC-001 npm run gates"
cap review-cognitive "npm run gate:review"
echo "// reviewed" >> services/position-service/src/app.ts
cap review-human "npm run gate:review"
git checkout -q -- services/position-service/src/app.ts
git checkout -q -- . && git clean -fdq services test

git apply labs/patches/attempt-c-edit-the-model.patch
cap attempt-c-gates "SPEC=SPEC-001 npm run gates"
git checkout -q -- . && git clean -fdq services test specs

git apply labs/patches/spec-002-model-change.patch
cap spec-002-model "SPEC=SPEC-002 npm run gates"
git apply labs/patches/attempt-d-spec-002.patch
cap spec-002-impl "SPEC=SPEC-002 npm run gates"
git checkout -q -- . && git clean -fdq services test specs

git apply labs/patches/attempt-b-conformant.patch
git add -A && git commit -q -m "Add account summary endpoint" -m "Spec: SPEC-001"
cap evidence "CHANGE_AUTHOR_KIND=agent CHANGE_AUTHOR_ID=my-coding-agent npm run evidence"
BUNDLE=$(ls evidence/out/*.json | head -1)
cap evidence-json "node -e \"const b=JSON.parse(require('fs').readFileSync('$BUNDLE'));const g=b.gates.map(x=>({gate:x.gate,passed:x.passed,controls:x.controls}));console.log(JSON.stringify({schema:b.schema,subject:{commit:b.subject.commit.slice(0,12)+'...',spec:b.subject.spec,architectureSha256:b.subject.architectureSha256.slice(0,16)+'...',changedFiles:b.subject.changedFiles},author:b.author,admissible:b.admissible,review:{requiredMode:b.review.requiredMode,authorMayNotReview:b.review.authorMayNotReview},controls:b.controls,gates:g,sha256:b.sha256.slice(0,16)+'...'},null,2))\""

mv "$TMP" "$OUT"
echo "wrote $OUT ($(grep -c 'window.CAPTURES\[' "$OUT") captures)"
